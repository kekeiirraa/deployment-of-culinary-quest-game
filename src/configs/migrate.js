// database migration for postgres (neon)
// creates every table the app needs and seeds the reference data.
// safe to run repeatedly - it is used on every deploy - because all DDL uses
// IF NOT EXISTS and all seed rows use ON CONFLICT DO NOTHING.
//
// run with: npm run migrate

const db = require('../services/db');

// note on identifiers: postgres folds unquoted names to lowercase, so
// "CREATE TABLE ChefRanks" and "FROM ChefRanks" both resolve to chefranks.
// the CA1 table named "User" had to be renamed to "Users" because USER is a
// reserved word in postgres.
const SCHEMA = `
CREATE TABLE IF NOT EXISTS ChefRanks (
  rank_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rank_name VARCHAR(255) NOT NULL,
  min_points INT NOT NULL,
  special_ability VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS Users (
  user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255),
  points INT DEFAULT 0,
  current_rank_id INT REFERENCES ChefRanks(rank_id)
);

CREATE TABLE IF NOT EXISTS ChallengeCategory (
  category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  icon VARCHAR(20),
  description TEXT
);

CREATE TABLE IF NOT EXISTS WellnessChallenge (
  challenge_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id INT NOT NULL REFERENCES Users(user_id),
  description TEXT NOT NULL,
  points INT NOT NULL,
  category_id INT REFERENCES ChallengeCategory(category_id)
);

CREATE TABLE IF NOT EXISTS UserCompletion (
  completion_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id INT NOT NULL REFERENCES WellnessChallenge(challenge_id),
  user_id INT NOT NULL REFERENCES Users(user_id),
  details TEXT,
  completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Badges (
  badge_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  badge_name VARCHAR(255) NOT NULL,
  description TEXT
);

CREATE TABLE IF NOT EXISTS UserBadges (
  user_id INT NOT NULL REFERENCES Users(user_id),
  badge_id INT NOT NULL REFERENCES Badges(badge_id),
  earned_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, badge_id)
);

CREATE TABLE IF NOT EXISTS Recipes (
  recipe_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_name VARCHAR(255) NOT NULL,
  description TEXT,
  required_points INT
);

CREATE TABLE IF NOT EXISTS UserRecipes (
  user_id INT NOT NULL REFERENCES Users(user_id),
  recipe_id INT NOT NULL REFERENCES Recipes(recipe_id),
  unlocked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, recipe_id)
);

CREATE TABLE IF NOT EXISTS Ingredient (
  ingredient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  icon VARCHAR(20),
  type VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS UserIngredient (
  user_id INT NOT NULL REFERENCES Users(user_id),
  ingredient_id INT NOT NULL REFERENCES Ingredient(ingredient_id),
  quantity INT DEFAULT 0,
  PRIMARY KEY (user_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS RecipeIngredient (
  recipe_id INT NOT NULL REFERENCES Recipes(recipe_id),
  ingredient_id INT NOT NULL REFERENCES Ingredient(ingredient_id),
  quantity INT DEFAULT 1,
  PRIMARY KEY (recipe_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS RecipeReview (
  review_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES Users(user_id),
  recipe_id INT NOT NULL REFERENCES Recipes(recipe_id),
  rating INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
`;

