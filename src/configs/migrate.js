// the seed rows above use explicit ids, which leaves each identity sequence
// behind the highest id. bump every sequence past its table's max id so the
// next real insert does not collide with seeded data.
const RESET_SEQUENCES = `
SELECT setval(pg_get_serial_sequence('chefranks', 'rank_id'), COALESCE((SELECT MAX(rank_id) FROM ChefRanks), 1));
SELECT setval(pg_get_serial_sequence('users', 'user_id'), COALESCE((SELECT MAX(user_id) FROM Users), 1));
SELECT setval(pg_get_serial_sequence('challengecategory', 'category_id'), COALESCE((SELECT MAX(category_id) FROM ChallengeCategory), 1));
SELECT setval(pg_get_serial_sequence('wellnesschallenge', 'challenge_id'), COALESCE((SELECT MAX(challenge_id) FROM WellnessChallenge), 1));
SELECT setval(pg_get_serial_sequence('usercompletion', 'completion_id'), COALESCE((SELECT MAX(completion_id) FROM UserCompletion), 1));
SELECT setval(pg_get_serial_sequence('badges', 'badge_id'), COALESCE((SELECT MAX(badge_id) FROM Badges), 1));
SELECT setval(pg_get_serial_sequence('recipes', 'recipe_id'), COALESCE((SELECT MAX(recipe_id) FROM Recipes), 1));
SELECT setval(pg_get_serial_sequence('ingredient', 'ingredient_id'), COALESCE((SELECT MAX(ingredient_id) FROM Ingredient), 1));
SELECT setval(pg_get_serial_sequence('recipereview', 'review_id'), COALESCE((SELECT MAX(review_id) FROM RecipeReview), 1));
`;

async function migrate() {
    console.log('Running migration...');

    await db.raw(SCHEMA);
    console.log('  tables ready');

    await db.raw(SEED);
    console.log('  reference data seeded');

    await db.raw(RESET_SEQUENCES);
    console.log('  id sequences aligned');

    console.log('Migration complete.');
}

// only run automatically when executed directly (npm run migrate), so tests can
// import and call migrate() themselves
if (require.main === module) {
    migrate()
        .then(() => db.end())
        .then(() => process.exit(0))
        .catch((error) => {
            console.error('Migration failed:', error.message);
            process.exit(1);
        });
}

module.exports = { migrate };
